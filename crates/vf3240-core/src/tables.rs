#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn init_table_has_unique_low_bank_addresses() {
        let mut seen = std::collections::HashSet::new();
        for &(addr, _) in ASIC_INIT_REG.iter() {
            assert!(
                addr < 0x100,
                "init table addr 0x{addr:03x} is not in the low bank"
            );
            assert!(seen.insert(addr), "duplicate init table addr 0x{addr:03x}");
        }
        assert_eq!(ASIC_INIT_REG[ASIC_INIT_GPIO_INDEX], (0x032, 0x69));
    }

    #[test]
    fn curve2_is_strictly_increasing_with_documented_counts() {
        assert!(CURVE_DATA2.windows(2).all(|w| w[0] < w[1]));
        assert_eq!(CURVE_DATA2[0], 5.0);
        assert_eq!(CURVE_DATA2[509], 2096.0);
        assert_eq!(CURVE_DATA2.iter().filter(|&&v| v < 1900.0).count(), 359);
        assert_eq!(CURVE_DATA2.iter().filter(|&&v| v < 1722.65).count(), 265);
        assert_eq!(CURVE_DATA2.iter().filter(|&&v| v < 1500.0).count(), 180);
    }
}
